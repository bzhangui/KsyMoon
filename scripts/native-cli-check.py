"""Run the standalone Native CLI against checked-in and original upstream inputs."""

import json
import os
from pathlib import Path
import platform
import runpy
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CORPUS = runpy.run_path(str(ROOT / "scripts/compatibility-report.py"))


def moon(*args, cwd=ROOT):
    subprocess.run(["moon", *args], cwd=cwd, check=True, timeout=180)


def verify(cli, work):
    def run(*args, status=0):
        result = subprocess.run(
            [str(cli), *map(str, args)], cwd=work, text=True, encoding="utf-8",
            capture_output=True, timeout=30,
        )
        assert result.returncode == status, (args, result.returncode, result.stdout, result.stderr)
        return result

    inputs = work / "project inputs"
    CORPUS["extract_formats"](CORPUS["corpus_archive"](), inputs)
    udp = inputs / "udp_datagram.ksy"
    shutil.copyfile(ROOT / "fixtures/udp_datagram.ksy", udp)
    imports = inputs / "imports_rel_1.ksy"
    zlib = inputs / "zlib_with_header_78.ksy"
    invalid = inputs / "invalid.ksy"
    invalid.write_text("meta: {id: invalid}\nseq: [{id: field, type: u1, if: 1}]\n", encoding="utf-8")

    checked = json.loads(run("check", udp, "--json").stdout)
    assert checked == {"file": str(udp), "ok": True, "diagnostics": []}, checked
    failed = json.loads(run("check", invalid, "--json", status=1).stdout)
    assert failed["ok"] is False and failed["file"] == str(invalid), failed
    assert failed["diagnostics"] == [{
        "code": "invalid_schema", "schema_path": "seq[0].if", "message": "expected a boolean expression",
    }], failed
    missing = json.loads(run("check", work / "missing.ksy", "--json", status=1).stdout)
    assert missing["diagnostics"][0]["code"] == "io_error", missing
    outside = json.loads(run("check", udp, "--root", inputs / "for_rel_imports", "--json", status=1).stdout)
    assert outside["diagnostics"][0]["code"] == "command_error", outside

    graph = json.loads(run("deps", imports).stdout)
    assert graph == {"entry": "imports_rel_1.ksy", "dependencies": [
        {"from": "imports_rel_1.ksy", "import_name": "for_rel_imports/imported_1", "to": "for_rel_imports/imported_1.ksy"},
        {"from": "for_rel_imports/imported_1.ksy", "import_name": "imported_2", "to": "for_rel_imports/imported_2.ksy"},
    ]}, graph
    absolute = json.loads(run("deps", inputs / "imports_abs_abs.ksy", "-I", inputs / "ks_path").stdout)
    assert len(absolute["dependencies"]) == 2, absolute
    assert all(edge["to"].startswith("ks_path/") for edge in absolute["dependencies"]), absolute

    output = work / "single.mbt"
    output.write_bytes(b"// existing content\n")
    run("generate", invalid, "--out", output, status=1)
    assert output.read_bytes() == b"// existing content\n"
    run("generate", udp, "--out", output)

    consumer = work / "consumer"
    consumer.mkdir()
    (consumer / "moon.mod").write_text('name = "verification/native-cli"\nversion = "0.1.0"\n', encoding="utf-8")
    generated = consumer / "generated"
    run("batch", "--out-dir", generated, udp, invalid, status=1)
    assert not generated.exists()
    run("batch", "--out-dir", generated, udp, udp, status=1)
    assert not generated.exists()
    run("batch", "--out-dir", generated, udp, imports, zlib)
    parser = generated / "udp_datagram"
    assert (parser / "udp_datagram.mbt").read_bytes() == output.read_bytes()
    assert "@ksy_zlib" in (generated / zlib.stem / "moon.pkg").read_text(encoding="utf-8")
    manifest = parser / "moon.pkg"
    manifest.write_bytes(b"// existing configuration\n")
    run("batch", "--out-dir", generated, udp, imports, zlib)
    assert manifest.read_bytes() == b"// existing configuration\n"
    assert not list(work.rglob("*.tmp"))

    (parser / "udp_wbtest.mbt").write_text(
        'test "UDP generated by the native CLI handles valid and truncated input" {\n'
        '  let data = b"\\x04\\xD2\\x16\\x2E\\x00\\x0B\\x00\\x00ABC"\n'
        '  let frame = parse_udp_datagram(data)\n'
        '  assert_eq(frame.src_port, 1234U)\n'
        '  assert_eq(frame.dst_port, 5678U)\n'
        '  assert_eq(frame.body.to_owned(), b"ABC")\n'
        '  let truncated = b"\\x04\\xD2\\x16\\x2E\\x00\\x0B\\x00\\x00AB"\n'
        '  let rejected = try { ignore(parse_udp_datagram(truncated)); false } catch { _ => true }\n'
        '  assert_true(rejected)\n'
        '}\n', encoding="utf-8",
    )
    moon("check", "--frozen", "--target", "all", "--deny-warn", cwd=consumer)
    moon("build", "--frozen", "--target", "all", "--deny-warn", cwd=consumer)
    moon("test", "--frozen", "--target", "all", "--deny-warn", cwd=consumer)


def main():
    moon("build", "--frozen", "--release", "--target", "native", "--deny-warn", "cmd/ksymoon_native")
    binary = ROOT / "_build/native/release/build/cmd/ksymoon_native/ksymoon_native"
    candidates = [binary.with_suffix(".exe"), binary] if os.name == "nt" else [binary, binary.with_suffix(".exe")]
    cli = next(candidate for candidate in candidates if candidate.is_file())
    with tempfile.TemporaryDirectory(prefix="native-cli-", dir=ROOT / "_build") as work:
        verify(cli, Path(work))
    report = {
        "source_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "platform": platform.system(),
        "standalone_executable": cli.name,
        "commands": ["check --json", "deps", "generate", "batch"],
        "upstream_revision": CORPUS["REVISION"],
        "consumer_targets": ["js", "wasm", "wasm-gc", "native"],
        "verified": True,
    }
    (ROOT / "_build/native-cli-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"Native CLI verified on {report['platform']}; generated consumer passed all four targets")


if __name__ == "__main__":
    main()
